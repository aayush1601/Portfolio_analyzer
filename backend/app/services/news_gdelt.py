"""Historical news backfill from GDELT (ADR 0001 option b, ADR 0003): makes RQ3 answerable.

RSS has no history and the GDELT DOC API only searches a rolling recent window, so the history comes from
the GDELT Global Knowledge Graph in Google BigQuery (public dataset `gdelt-bq.gdeltv2.gkg_partitioned`).
The BigQuery sandbox is free (no card; 1 TB of queries a month) and refuses, rather than bills, a query
over the quota.

  uv run python -m app.services.news_gdelt sql [START] [END] > gdelt.sql   # 1. print the query
  # 2. run it at console.cloud.google.com/bigquery and save the result as CSV
  uv run python -m app.services.news_gdelt import gdelt.csv [more.csv …]   # 3. raw JSONL + history store
  uv run --group ml python -m app.services.sentiment score                 # 4. FinBERT, locally

Output: data/raw/news/gdelt/YYYY-MM.jsonl (RawNewsItem, as the RSS collector writes) and the processed store
data/processed/news_history/, which load_news() reads together with the live store. It is a separate store
so the 30-minute cloud job never reprocesses (or re-queues) years of history.

Timing: GKG's DATE is the 15-minute batch in which GDELT saw the article, minutes to hours after publication.
It is used as published_at, so a backtest at time t can only see an article after GDELT could have: late,
never early (no look-ahead).
"""

import csv
import json
import logging
import sys
from collections import defaultdict
from datetime import UTC, date, datetime
from pathlib import Path

import yaml

from app.config import get_settings
from app.services.news_rss import RawNewsItem, clean_text, news_id

log = logging.getLogger(__name__)
TABLE = "gdelt-bq.gdeltv2.gkg_partitioned"
RE2_SPECIAL = set(r"\.^$|?*+()[]{}")


def re2_escape(text: str) -> str:
    """Escape for RE2 (BigQuery). Python's re.escape also escapes spaces and '&', which RE2 rejects."""
    return "".join(f"\\{c}" if c in RE2_SPECIAL else c for c in text)


def gdelt_config(config_dir: Path) -> dict:
    return yaml.safe_load((config_dir / "news_sources.yaml").read_text())["gdelt"]


def source_name(domain: str) -> str:
    return f"gdelt:{domain}"


def reliability(config_dir: Path) -> dict[str, float]:
    """Source name → reliability, for the News Impact score (merged into news_pipeline.Mapper)."""
    return {source_name(d): r for d, r in gdelt_config(config_dir)["domains"].items()}


def build_query(config_dir: Path, start: date, end: date) -> str:
    """BigQuery SQL: titles from Indian business publishers that mention a universe company or sector.

    The title filter is deliberately loose (word boundaries only); news_pipeline.Mapper does the exact
    matching, stop phrases included, after import. Only the four columns needed are read, which keeps
    the scan small.
    """
    u = yaml.safe_load((config_dir / "universe.yaml").read_text())
    n = yaml.safe_load((config_dir / "news_sources.yaml").read_text())
    aliases = sorted({a for s in u["stocks"] for a in s["aliases"]}, key=len, reverse=True)
    sectors = sorted({k for kws in n["sector_keywords"].values() for k in kws}, key=len, reverse=True)
    company_re = r"(^|[^\w&])(" + "|".join(map(re2_escape, aliases)) + r")([^\w&]|$)"
    sector_re = r"(?i)(^|\W)(" + "|".join(map(re2_escape, sectors)) + r")(\W|$)"
    domains = ", ".join(f"'{d}'" for d in gdelt_config(config_dir)["domains"])
    title = r"REGEXP_EXTRACT(Extras, r'<PAGE_TITLE>(.*?)</PAGE_TITLE>')"
    # Built only from our own config files (universe aliases, publisher list), never from user input.
    return f"""-- Generated by app.services.news_gdelt; {start} to {end}.
-- Before running, check the estimate at the top right of the editor ("This query will process …").
-- The sandbox allows 1 TB a month: if the estimate is larger, shorten the dates and run the rest next month.
WITH articles AS (
  SELECT
    FORMAT_TIMESTAMP('%Y-%m-%dT%H:%M:%SZ', PARSE_TIMESTAMP('%Y%m%d%H%M%S', CAST(DATE AS STRING))) AS seen_at,
    SourceCommonName AS domain,
    DocumentIdentifier AS url,
    {title} AS title
  FROM `{TABLE}`
  WHERE _PARTITIONTIME >= TIMESTAMP('{start}') AND _PARTITIONTIME < TIMESTAMP('{end}')
    AND SourceCommonName IN ({domains})
)
SELECT seen_at, domain, url, title
FROM articles
WHERE title IS NOT NULL
  AND (REGEXP_CONTAINS(title, r'''{company_re}''') OR REGEXP_CONTAINS(title, r'''{sector_re}'''))
ORDER BY seen_at
"""  # noqa: S608


def read_rows(paths: list[Path]) -> list[RawNewsItem]:
    items: dict[str, RawNewsItem] = {}
    for path in paths:
        with path.open(newline="", encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                title, url = clean_text(row.get("title")), (row.get("url") or "").strip()
                if not title or not url or not row.get("seen_at"):
                    continue
                seen = datetime.fromisoformat(row["seen_at"].replace("Z", "+00:00")).astimezone(UTC)
                item = RawNewsItem(
                    news_id=news_id(url, title),
                    source=source_name(row["domain"].strip().lower()),
                    url=url,
                    headline=title,
                    summary="",
                    published_at=seen,  # conservative: when GDELT saw it (see module docstring)
                    ingested_at=seen,
                )
                items.setdefault(item.news_id, item)  # GKG can list a URL more than once
    return sorted(items.values(), key=lambda i: i.ingested_at)


def write_raw(items: list[RawNewsItem], out_dir: Path) -> None:
    """One JSONL file per month, rewritten in full so a re-import never duplicates."""
    by_month: dict[str, list[RawNewsItem]] = defaultdict(list)
    for i in items:
        by_month[i.ingested_at.strftime("%Y-%m")].append(i)
    out_dir.mkdir(parents=True, exist_ok=True)
    for month, rows in by_month.items():
        f = out_dir / f"{month}.jsonl"
        old = (
            [RawNewsItem(**json.loads(line)) for line in f.read_text().splitlines() if line]
            if f.exists()
            else []
        )
        merged = {r.news_id: r for r in old + rows}
        f.write_text(
            "".join(r.model_dump_json() + "\n" for r in sorted(merged.values(), key=lambda r: r.ingested_at))
        )


def build_history(settings=None) -> int:
    """Raw GDELT JSONL → processed news_history store (same schema and mapping as the live store)."""
    from app.services.market_data import save
    from app.services.news_pipeline import Mapper, load_raw, process

    settings = settings or get_settings()
    raw = load_raw(settings.data_dir / "raw" / "news" / "gdelt")
    if raw.empty:
        return 0
    news = process(raw, Mapper.from_config(settings.config_dir))
    # Keep only articles that name a universe company or sector: the SQL filter is looser than the Mapper.
    news = news[news["symbols"].str.len().gt(0) | news["sectors"].str.len().gt(0)]
    save(news, settings.data_dir / "processed" / "news_history")
    return len(news)


def main() -> None:
    from app.utils.log import setup_logging

    settings = get_settings()
    setup_logging(settings.log_level)
    cmd, *args = sys.argv[1:] or ["help"]
    if cmd == "sql":
        cfg = gdelt_config(settings.config_dir)
        start = date.fromisoformat(args[0]) if args else date.fromisoformat(str(cfg["start"]))
        end = date.fromisoformat(args[1]) if len(args) > 1 else date.today()
        print(build_query(settings.config_dir, start, end))
    elif cmd == "import" and args:
        items = read_rows([Path(a) for a in args])
        write_raw(items, settings.data_dir / "raw" / "news" / "gdelt")
        kept = build_history(settings)
        log.info("gdelt import done", extra={"fields": {"rows": len(items), "kept_in_history": kept}})
        print(f"imported {len(items)} headlines; {kept} name a universe company or sector")
    else:
        sys.exit("usage: python -m app.services.news_gdelt sql [START] [END] | import <csv> [<csv> …]")


if __name__ == "__main__":
    main()
